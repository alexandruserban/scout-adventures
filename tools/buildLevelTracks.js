// Bundles the level soundtracks (src/level-soundtrack/*.mid) into src/audio/levelTracks.js
// as base64, so the game can play them without fetch() (which fails on file:// and inside
// the Flutter WebView's local assets).
// Usage: node tools/buildLevelTracks.js   (re-run whenever a .mid file is added or changed)
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'src', 'level-soundtrack');
const OUTPUT_FILE = path.join(ROOT, 'src', 'audio', 'levelTracks.js');

const files = fs.readdirSync(SOURCE_DIR).filter(name => name.toLowerCase().endsWith('.mid')).sort();
const entries = files.map(name => {
  const key = path.basename(name, path.extname(name));
  const base64 = fs.readFileSync(path.join(SOURCE_DIR, name)).toString('base64');
  return `    '${key}': '${base64}'`;
});

const output = `/**
 * GENERATED by tools/buildLevelTracks.js from src/level-soundtrack/*.mid. Do not edit by hand.
 * Each level's MIDI soundtrack, base64-encoded, keyed by file name (without .mid).
 */
(function (Forest) {
  Forest.LevelTracks = Object.freeze({
${entries.join(',\n')}
  });
})(window.Forest);
`;

fs.writeFileSync(OUTPUT_FILE, output);
console.log(`Wrote ${files.length} tracks to ${path.relative(ROOT, OUTPUT_FILE)}`);
