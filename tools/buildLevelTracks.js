// Bundles the level soundtracks (src/level-soundtrack/*.mid) into src/audio/levelTracks.js,
// and the boss fight themes (src/boss-soundtrack/*.mid) into src/audio/bossTracks.js,
// as base64, so the game can play them without fetch() (which fails on file:// and inside
// the Flutter WebView's local assets).
// Usage: node tools/buildLevelTracks.js   (re-run whenever a .mid file is added or changed)
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

/** Write every .mid in `sourceDir` to `outputFile` as `Forest[name]`, keyed by file name (without .mid). */
function bundle(sourceDir, outputFile, name, description) {
  const files = fs.readdirSync(sourceDir).filter(file => file.toLowerCase().endsWith('.mid')).sort();
  const entries = files.map(file => {
    const key = path.basename(file, path.extname(file));
    const base64 = fs.readFileSync(path.join(sourceDir, file)).toString('base64');
    return `    '${key}': '${base64}'`;
  });
  const source = path.relative(ROOT, sourceDir).split(path.sep).join('/');
  const output = `/**
 * GENERATED by tools/buildLevelTracks.js from ${source}/*.mid. Do not edit by hand.
 * ${description}, base64-encoded, keyed by file name (without .mid).
 */
(function (Forest) {
  Forest.${name} = Object.freeze({
${entries.join(',\n')}
  });
})(window.Forest);
`;
  fs.writeFileSync(outputFile, output);
  console.log(`Wrote ${files.length} tracks to ${path.relative(ROOT, outputFile)}`);
}

bundle(path.join(ROOT, 'src', 'level-soundtrack'), path.join(ROOT, 'src', 'audio', 'levelTracks.js'), 'LevelTracks', "Each level's MIDI soundtrack");
bundle(path.join(ROOT, 'src', 'boss-soundtrack'), path.join(ROOT, 'src', 'audio', 'bossTracks.js'), 'BossTracks', "Each boss's MIDI fight theme");
